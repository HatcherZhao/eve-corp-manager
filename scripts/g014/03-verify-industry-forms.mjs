import assert from 'node:assert/strict'

const task = await taskSpace(48)
const page = task.page('p1')
assert.equal(new URL(await page.url()).origin, 'http://127.0.0.1:5173')
assert.equal(await page.evaluate(() => !!window.__industryFixture), true)
if (await page.evaluate(() => [...document.querySelectorAll('.arco-modal')].some((modal) => modal.getBoundingClientRect().width > 0))) await page.click('loc=role:button[name="Close"]')
await page.evaluate(() => { window.__industryFixture.writes.length = 0 })
await page.evaluate(() => window.__industryFixture.router.push('/eve/industry/config'))
await page.waitForSelector('.industry-config-page', { state: 'visible' })
await page.click('text="生产配置"')
await page.waitForFunction(() => document.querySelector('.arco-tabs-content-item-active')?.innerText.includes('配置名称'))
await page.click('.arco-tabs-content-item-active button')
await page.waitForFunction(() => [...document.querySelectorAll('.industry-settings-modal')].some((modal) => modal.getBoundingClientRect().width > 0))
await page.evaluate(() => Promise.all(document.getAnimations().filter((animation) => animation.effect?.getTiming().iterations !== Infinity).map((animation) => animation.finished.catch(() => undefined))))
const values = await page.evaluate(() => [...document.querySelectorAll('.industry-settings-modal input')].filter((input) => input.getClientRects().length).map((input) => input.value))
assert.deepEqual(values, ['测试生产配置', '7', '10', '11', '80', '3.6', '1'])

const layouts = []
for (const width of [320, 375, 414, 768, 1024, 1280, 1440]) {
  await page.cdp('Emulation.setDeviceMetricsOverride', { width, height: 1000, deviceScaleFactor: 1, mobile: false })
  await page.waitForFunction((expected) => window.innerWidth === expected, width)
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const layout = await page.evaluate(() => {
    const modal = document.querySelector('.industry-settings-modal')
    const rect = modal.getBoundingClientRect()
    const clipped = [...modal.querySelectorAll('.arco-form-item-label')].filter((label) => label.scrollWidth > label.clientWidth + 1).map((label) => label.textContent)
    return { width: innerWidth, left: rect.left, right: rect.right, modalOverflow: modal.scrollWidth - modal.clientWidth, clipped }
  })
  assert.ok(layout.left >= 0 && layout.right <= width + 1, JSON.stringify(layout))
  assert.ok(layout.modalOverflow <= 1, JSON.stringify(layout))
  assert.deepEqual(layout.clipped, [], JSON.stringify(layout))
  layouts.push(layout)
  if (width === 320 || width === 1440) await page.screenshot({ path: `/Users/yuqingzhao/_workspace/_AI/eve-corp-manager/tmp/g014/production-settings-${width}.png` })
}
await page.fill('.industry-settings-modal .industry-settings-grid .arco-form-item:nth-child(3) input', '')
await page.press('.industry-settings-modal .industry-settings-grid .arco-form-item:nth-child(3) input', 'Tab')
await page.click('.industry-settings-modal .arco-modal-footer .arco-btn-primary')
assert.equal(await page.evaluate(() => window.__industryFixture.writes.length), 0)
assert.equal(await page.evaluate(() => document.querySelector('.industry-settings-modal').getBoundingClientRect().width > 0), true)
await page.fill('.industry-settings-modal .industry-settings-grid .arco-form-item:nth-child(3) input', '11')
await page.fill('.industry-settings-modal .industry-settings-grid .arco-form-item:nth-child(5) input', '4')
await page.press('.industry-settings-modal .industry-settings-grid .arco-form-item:nth-child(5) input', 'Tab')
await page.click('.industry-settings-modal .arco-modal-footer .arco-btn-primary')
await page.waitForFunction(() => window.__industryFixture.writes.length === 1)
const saved = await page.evaluate(() => window.__industryFixture.writes[0])
assert.equal(saved.url, '/eve/industry/configs/cfg1')
assert.deepEqual(JSON.parse(saved.payload.productionSkillJson), { productionLines: 11, timeMultiplier: 0.8, extraSkill: 5 })
assert.deepEqual(JSON.parse(saved.payload.marketFeeJson), { salesTax: 0.04, brokerFee: 0.01, extraFee: 0.02 })
assert.equal(saved.payload.freshnessPolicyJson, '{"marketMinutes":30}')
assert.equal(saved.payload.marketShareLimit, 0.1)
await page.waitForFunction(() => ![...document.querySelectorAll('.industry-settings-modal')].some((modal) => modal.getBoundingClientRect().width > 0))
await page.click('text="蓝图配置"')
await page.waitForFunction(() => document.querySelector('.arco-tabs-content-item-active')?.innerText.includes('蓝图拷贝'))
console.log({ layouts, invalidFormBlocked: true, originalFieldsPreserved: true })
await page.click('.arco-tabs-content-item-active button')
await page.waitForFunction(() => [...document.querySelectorAll('.industry-settings-modal')].some((modal) => modal.getBoundingClientRect().width > 0))
await page.evaluate(() => Promise.all(document.getAnimations().filter((animation) => animation.effect?.getTiming().iterations !== Infinity).map((animation) => animation.finished.catch(() => undefined))))
assert.match(await page.evaluate(() => [...document.querySelectorAll('.industry-settings-modal')].find((modal) => modal.getBoundingClientRect().width > 0).innerText), /材料效率（%）/)
assert.match(await page.evaluate(() => [...document.querySelectorAll('.industry-settings-modal')].find((modal) => modal.getBoundingClientRect().width > 0).innerText), /时间效率（%）/)
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 320, height: 1000, deviceScaleFactor: 1, mobile: false })
await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
await page.screenshot({ path: '/Users/yuqingzhao/_workspace/_AI/eve-corp-manager/tmp/g014/blueprint-settings-320.png' })
await page.click('loc=role:button[name="Close"]')
await page.waitForFunction(() => ![...document.querySelectorAll('.arco-modal')].some((modal) => modal.getBoundingClientRect().width > 0))
await page.cdp('Emulation.clearDeviceMetricsOverride')
console.log({ layouts, saved: { salesTax: JSON.parse(saved.payload.marketFeeJson).salesTax, preservedExtraFields: true }, invalidFormBlocked: true, blueprintLabels: '材料效率、时间效率' })
console.log(await page.snapshot({ scope: 'full_page' }))
